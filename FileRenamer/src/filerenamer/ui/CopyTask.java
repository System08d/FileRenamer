package filerenamer.ui;

/**
 *
 * @author siste
 */

import filerenamer.logic.RenameStrategy;
import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.util.List;
import java.util.concurrent.ExecutionException;
import java.util.function.BiConsumer;
import javax.swing.JProgressBar;
import javax.swing.SwingWorker;

/**
 * Copies files to the output folder using names generated by a
 * {@link RenameStrategy}.
 *
 * Copying runs in a background thread. Progress updates and the
 * completion callback are handled on the Swing event dispatch thread.
 */

public class CopyTask extends SwingWorker<int[], Integer> {

    private static final java.util.logging.Logger logger =
            java.util.logging.Logger.getLogger(CopyTask.class.getName());

    private final List<File> files;
    private final RenameStrategy strategy;
    private final File outputFolder;
    private final JProgressBar progressBar;
    private final BiConsumer<Integer, Integer> onFinished;

/**
 * Creates a background task for copying files with generated names.
 *
 * @param files files to copy
 * @param strategy strategy used to generate file names
 * @param outputFolder destination directory
 * @param progressBar progress indicator updated during copying
 * @param onFinished callback receiving the number of copied files
 *                   and the number of errors
 */
    
    public CopyTask(List<File> files,
            RenameStrategy strategy,
            File outputFolder,
            JProgressBar progressBar,
            BiConsumer<Integer, Integer> onFinished) {
        this.files = files;
        this.strategy = strategy;
        this.outputFolder = outputFolder;
        this.progressBar = progressBar;
        this.onFinished = onFinished;
    }

/**
 * Copies the files and publishes progress updates as processing advances.
 *
 * @return an array containing the number of copied files at index 0
 *         and the number of errors at index 1
 */

    @Override
    protected int[] doInBackground() {
        int copied = 0;
        int errors = 0;
        int index = 1;

        for (File f : files) {
            if (isCancelled()) {
                break;
            }

            try {
                File dest = uniqueDestination(f, index);
                Files.copy(f.toPath(), dest.toPath());
                copied++;
            } catch (IOException | RuntimeException ex) {
                errors++;
                logger.log(java.util.logging.Level.WARNING,
                        "Failed to copy: " + f.getName(), ex);
            }

            publish(index);
            index++;
        }

        return new int[]{copied, errors};
    }

/**
 * Updates the progress bar on the Swing event dispatch thread.
 *
 * When multiple progress updates are batched together, the most
 * recent processed-file count is displayed.
 */ 
    
    @Override
    protected void process(List<Integer> chunks) {
        progressBar.setValue(chunks.get(chunks.size() - 1));
    }

/**
 * Handles task completion on the Swing event dispatch thread
 * and reports the final copy results through the callback.
 */

    @Override
    protected void done() {
        progressBar.setValue(progressBar.getMaximum());
        try {
            int[] result = get();
            onFinished.accept(result[0], result[1]);
        } catch (InterruptedException | ExecutionException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Copy task failed", ex);
            onFinished.accept(0, files.size());
        }
    }

/**
 * Generates a destination path with a unique file name.
 *
 * The generated base name and original extension are preserved.
 * If the destination already exists, a numeric suffix is appended
 * before the extension, starting with {@code (2)}.
 *
 * @param source original file being copied
 * @param index one-based file index passed to the naming strategy
 * @return destination path that does not currently exist
 */

    private File uniqueDestination(File source, int index) {
        String name = source.getName();
        int dotIndex = name.lastIndexOf('.');
        String extension = (dotIndex > 0) ? name.substring(dotIndex) : "";

        String baseName = strategy.generateName(source, index);
        File dest = new File(outputFolder, baseName + extension);

        int n = 2;
        while (dest.exists()) {
            dest = new File(outputFolder, baseName + " (" + n + ")" + extension);
            n++;
        }
        return dest;
    }
}