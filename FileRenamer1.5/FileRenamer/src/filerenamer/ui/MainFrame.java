    private void btnChooseFolderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChooseFolderActionPerformed
    JFileChooser fileChooser = new JFileChooser();
    fileChooser.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
    fileChooser.setDialogTitle("Выберите исходную папку");

    int result = fileChooser.showOpenDialog(this);

    if (result == JFileChooser.APPROVE_OPTION) {
        selectedSourceFolder = fileChooser.getSelectedFile();
        lblFolderPath.setText(selectedSourceFolder.getAbsolutePath());
        loadFilesIntoList(selectedSourceFolder);
    }
    }//GEN-LAST:event_btnChooseFolderActionPerformed

    private void btnRenameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRenameActionPerformed
    if (selectedSourceFolder == null) {
        lblStatus.setText("Сначала выберите исходную папку");
        return;
    }
    if (selectedDestFolder == null) {
        lblStatus.setText("Сначала выберите папку для копий");
        return;
    }

    File[] files = selectedSourceFolder.listFiles();
if (files == null || files.length == 0) {
    lblStatus.setText("В исходной папке нет файлов");
    return;
}

sortFilesNaturally(files);

    String timestamp = LocalDateTime.now().format(
            DateTimeFormatter.ofPattern("yyyy-MM-dd_HH-mm-ss"));
    File outputFolder = new File(selectedDestFolder, "renamed_" + timestamp);

    if (!outputFolder.mkdirs()) {
        lblStatus.setText("Не удалось создать папку для копий");
        return;
    }

     RenameStrategy strategy = createStrategy();
     if (strategy == null) {
       lblStatus.setText("Выберите способ переименования");
      return;
     }

    int copiedCount = 0;
    int errorCount = 0;
    int index = 1;

    for (File f : files) {
        if (!f.isFile()) {
            continue;
        }

        String extension = "";
        String name = f.getName();
        int dotIndex = name.lastIndexOf('.');
        if (dotIndex > 0) {
            extension = name.substring(dotIndex);
        }

        String newName;
        File destFile;
        do {
            newName = strategy.generateName(f, index) + extension;
            destFile = new File(outputFolder, newName);
        } while (destFile.exists());

        try {
            Files.copy(f.toPath(), destFile.toPath());
            copiedCount++;
        } catch (IOException ex) {
            errorCount++;
            logger.log(java.util.logging.Level.WARNING, "Не удалось скопировать: " + f.getName(), ex);
        }

        index++;
    }

    lblStatus.setText("Скопировано: " + copiedCount
            + (errorCount > 0 ? ", ошибок: " + errorCount : "")
            + " → папка " + outputFolder.getName());
    }//GEN-LAST:event_btnRenameActionPerformed

